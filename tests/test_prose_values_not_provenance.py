# --- the two paths may never disagree ------------------------------------


@pytest.mark.parametrize(
    "key,value",
    [(k, v) for k in ("context", "generator", "note", "tool") for v in PROSE_VALUES]
    + [("generator", "Claude"), ("note", "c2pa manifest"), ("tool", "Gemini")],
)
def test_inspect_and_clean_agree(key: str, value: str) -> None:
    """A checker and the cleaner it gates must decide identically.

    They read the same helper now; this pins that they keep doing so. If they
    drift, `check` reports a file clean while `clean` silently deletes a key
    from it -- the failure mode this whole class of bug produces.
    """
    doc = _doc(key, value)
    flagged = named_value_is_ai(key, value)
    key_is_ai_by_name = f"frontmatter key: {key}" in inspect_markdown(doc)[2]

    cleaned, _ = clean_markdown(doc)
    dropped = f"{key}:" not in cleaned

    assert dropped == (flagged or key_is_ai_by_name)


def test_cleaned_output_is_no_longer_flagged() -> None:
    """Round-trip: whatever clean leaves behind must inspect clean."""
    text = _doc("generator", "Claude")
    cleaned, _ = clean_markdown(text)
    _c2, has_ai, findings, _d = inspect_markdown(cleaned)
    assert not has_ai, findings


