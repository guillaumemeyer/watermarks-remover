"""Document metadata *values* are prose until a naming key says otherwise.

Regression: `AI_META_NAME_RE` -- a vocabulary built to match metadata *names*
-- was matched against every frontmatter value as a bare substring. Ordinary
English then read as provenance: a note whose `context:` field said "a
generator produced 29 datasheets" hit on the word "generator".

In `check` mode that is a false warning. In `clean` mode the cleaner drops the
whole key *and every nested line under it*, so an author's own text is deleted
because they wrote a common noun. The file still parses afterwards, so nothing
downstream notices.

The rule restored here is the project's existing one, applied to Markdown:
image_meta scans values for product names only under naming keys
(Software/Creator/parameters) and matches unkeyed JPEG COM text against
unambiguous markers alone, precisely because "Claude Monet" and "Generated by
ImageMagick" are ordinary prose.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = ROOT / "service" / "scripts"
sys.path.insert(0, str(SCRIPTS))

from container_meta import (
    _meta_attrs,
    _meta_tag_is_ai,
    clean_html,
    clean_markdown,
    inspect_html,
    inspect_markdown,
    named_value_is_ai,
)

# Prose an author legitimately writes about their own subject. Every one of
# these contains a word from the *name* vocabulary and none is a provenance
# mark. Drawn from real documents: engineering notes, changelogs, docs about
# provenance tooling itself.
PROSE_VALUES = [
    "A generator produced 29 branded PDF datasheets, each stamped with a code.",
    "Binds where artefacts are cached (they run generators and gates)",
    "How to build a static site generator in Rust",
    "Notes on content provenance standards and their tradeoffs",
    "The digital source of the figures is the 2026 price list",
    "Claude Monet, water lilies, 1906",
    "Comparing OpenAI and Gemini pricing for the procurement review",
    "Why our AI generated captions needed a human pass",
]


def _doc(key: str, value: str) -> str:
    return f"---\ntitle: Demo\n{key}: {value}\nauthor: you\n---\nBody\n"


@pytest.mark.parametrize("value", PROSE_VALUES)
def test_prose_value_under_a_plain_key_is_not_flagged(value: str) -> None:
    _c2, has_ai, findings, _d = inspect_markdown(_doc("context", value))
    assert not has_ai, findings


@pytest.mark.parametrize("value", PROSE_VALUES)
def test_prose_value_survives_clean(value: str) -> None:
    """The destructive half: clean must not delete the author's own text."""
    cleaned, _actions = clean_markdown(_doc("context", value))
    assert value in cleaned
    assert "context:" in cleaned


def test_nested_block_under_a_prose_key_survives_clean() -> None:
    """A value hit drops nested children too, so the blast radius is bigger."""
    text = (
        "---\n"
        "title: Demo\n"
        "context: A generator produced the cards\n"
        "steps:\n"
        "  - measure\n"
        "  - verify\n"
        "---\n"
        "Body\n"
    )
    cleaned, _ = clean_markdown(text)
    assert "- measure" in cleaned
    assert "- verify" in cleaned
    assert "A generator produced the cards" in cleaned


